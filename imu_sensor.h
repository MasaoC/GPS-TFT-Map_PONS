// ============================================================
// File    : imu_sensor.h
// Project : PONS v7 (Pilot Oriented Navigation System for HPA)
// Role    : IMU チップと、その上に乗る推定（姿勢 ESKF・バリオ KF）の境界。
//           「どのチップでも同じ形で生データを流し込む口」と、
//           「そのチップに何が有るか／無いか」を表す能力ビットを定義する。
// Author  : MasaoC (@masao_mobile)
// Updated : 2026/10/03
// ============================================================
//
// ★ **この境界を作った理由。**
//   BNO085 を SCH16T-K01（Murata）へ差し替える予定だが、両者は種類が違う:
//     BNO085 … 中で融合までやる。姿勢・重力除去済み加速度・地磁気方位が出てくる
//     SCH16T … ジャイロと加速度しか出ない。融合は無い
//   0.983〜0.984 で機上の推定（ESKF・バリオ）から BNO085 の融合出力を全部外したので、
//   **必要なのはジャイロと加速度だけ**になった。残っている融合出力（GRV/RV）は
//   比較表示と健全性カウンタ専用で、無くなっても推定は成立する。
//   その「無くてもよい」を**型で表す**のがこのヘッダ。
//
// ---- 使い方 ----
//   ドライバ側（いまは imu.cpp 内の BNO085 部分）
//     ・生データが届いたら imu_feed_gyro() / imu_feed_accel() を呼ぶ。
//       これだけで姿勢 ESKF の伝播とバリオの蓄積がつながる。
//     ・自分に何が有るかを imu_caps() で申告する。
//     ★ **生ログ（imulog_push）はドライバ側に残してある。** レコードの
//       `s_us`（センサー時刻）と `acc`（申告精度）がチップ固有で、ここへ
//       移すと BNO085 時代のログとバイト互換でなくなる。退避済みの過去ログ
//       （〜2026-10-03）を同じツールで読み続けるため、形式は動かさない。
//   呼び出し側（画面・ログ）
//     ・融合出力に触る前に imu_caps() を見る。**「有って当然」と書かないこと。**
//       SCH16T では GRV / RV / LACC / 動的校正のどれも無い。
//
// ---- まだやっていないこと（SCH16T のドライバを書くときに） ----
//   imu.cpp は 1800 行あり、大半が BNO085 固有の「壊れやすい約束」
//   （sh2_close()・i2c バス復旧・未使用ピンの park・レポート飢餓対策）。
//   これを SCH16T 側に持ち込まないため、ファイルを割る:
//     imu.cpp         … バリオ KF・GNSS 観測・ゲッター（チップ非依存）
//     imu_bno08x.cpp  … 現 imu.cpp のチップ依存部を移動
//     imu_sch16t.cpp  … SCH16T ドライバ（tools/sch16t_test のフレーム層を持ち込む）
//   そのときドライバが実装する関数は次の形にする（**いまは宣言しない。
//   実体の無い宣言を置くとリンクが通るまで気づけないため**）:
//     bool imu_drv_setup();    void imu_drv_service();
//     bool imu_drv_alive();    bool imu_drv_recover();
//   ★ `imu_service_if_due()` の意味が変わる点に注意。BNO085 では
//     「読まないとレポートが溜まってジャイロが化ける」ための飢餓対策だが、
//     SCH16T は**こちらが SPI で取りに行く**ので飢餓が起きない（読まなければ
//     DRY が立ったままになるだけ）。**それでも飢餓対策のコメントは消さないこと。**
//     BNO085 に戻す可能性がある（CLAUDE.md の該当項目も同じ）。
//
#ifndef IMU_SENSOR_H
#define IMU_SENSOR_H

#include <Arduino.h>

// ============================================================
//  能力ビット — そのチップから「何が出てくるか」
// ============================================================
// ★ ジャイロと加速度は**全チップ必須**なので能力ビットを持たない。
//   無ければ姿勢もバリオも成立しないので、分岐させる意味が無い。
#define IMU_CAP_QUAT    (1u << 0)   // 融合クォータニオン（BNO085 の GRV 相当）
#define IMU_CAP_MAGYAW  (1u << 1)   // 磁北基準クォータニオン（RV 相当）＋ヘディング精度
#define IMU_CAP_MAG     (1u << 2)   // 生地磁気（0.984 で購読をやめたので BNO085 でも 0）
#define IMU_CAP_LINACC  (1u << 3)   // 重力除去済み加速度（LACC 相当）
#define IMU_CAP_CAL     (1u << 4)   // 動的校正と申告精度（BNO085 の DCD / accuracy）
#define IMU_CAP_STATUS  (1u << 5)   // 故障・飽和ステータス（SCH16T の S1:S0 / CE）

// いま載っているチップの能力。**融合出力に触る前にこれを見る。**
uint32_t imu_caps();
// ログ・画面に出す短い名前（"BNO085" / "SCH16T"）。
const char* imu_sensor_name();

// ============================================================
//  ドライバ → 推定 への口
// ============================================================
// ★ **チップ固有のコードが推定へ触るのはこの 2 つだけ。** 中で
//   姿勢 ESKF（attitude_on_*）とバリオの蓄積へ配る。生ログの push だけは
//   チップ側に残してある（上の「使い方」参照）。
//
// 単位と座標系（**守らないと静かに壊れる**）:
//   g[3] : センサー軸の角速度 [rad/s]。**バイアス補正前の生の値**
//          （ESKF が自分でバイアスを推定するので、引いて渡してはいけない）
//   a[3] : センサー軸の比力 [m/s²]。**重力を含んだまま**
//          （重力を引いた値を渡すと ESKF の伝播と水平化の両方が壊れる）
//   t_us : そのサンプルを受け取った時刻 [µs]（time_us_32()）。
//          **チップが付けたタイムスタンプを使わないこと。** BNO085 の
//          sv.timestamp は sh2 のアンダーフローで壊れている（0.983 の調査）。
void imu_feed_gyro(const float g[3], uint32_t t_us);
void imu_feed_accel(const float a[3]);

#endif // IMU_SENSOR_H
