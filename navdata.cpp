// プラットホームから北・南パイロンへの 2 等分線方位 [rad]（常に狭い側の二等分線）。
// ★ 入力座標の変化を監視して自動追従するキャッシュ設計（v7 と同じ）。
double pla_centerline_bearing_rad() {
  static double cached = NAN;
  static double k_pla_lat = NAN, k_pla_lon = NAN;
  static double k_n_lat   = NAN, k_n_lon   = NAN;
  static double k_s_lat   = NAN, k_s_lon   = NAN;

  const double p_lat = course_pla[0][0],    p_lon = course_pla[0][1];
  const double n_lat = course_npilon[0][0], n_lon = course_npilon[0][1];
  const double s_lat = course_spilon[0][0], s_lon = course_spilon[0][1];

  if (isnan(cached) ||
      p_lat != k_pla_lat || p_lon != k_pla_lon ||
      n_lat != k_n_lat   || n_lon != k_n_lon   ||
      s_lat != k_s_lat   || s_lon != k_s_lon) {
    double bn = calculateTrueCourseRad(deg2rad(p_lat), deg2rad(p_lon),
                                       deg2rad(n_lat), deg2rad(n_lon));
    double bw = calculateTrueCourseRad(deg2rad(p_lat), deg2rad(p_lon),
                                       deg2rad(s_lat), deg2rad(s_lon));
    cached = atan2(sin(bn) + sin(bw), cos(bn) + cos(bw));
    k_pla_lat = p_lat; k_pla_lon = p_lon;
    k_n_lat   = n_lat; k_n_lon   = n_lon;
    k_s_lat   = s_lat; k_s_lon   = s_lon;
  }
  return cached;
}

